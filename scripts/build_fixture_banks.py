def split_options(paragraph):
    """按 A．B．C．D． 切分选项，并取每一段中加粗的文字作为正确答案。"""
    chars = []
    for run in paragraph.runs:
        bold = bool(run.bold)
        for ch in run.text:
            chars.append((ch, bold))
    text = "".join(c for c, _ in chars)

    marks, expected = [], 0
    for match in re.finditer(r"([A-D])[．.、]", text):
        if expected < 4 and match.group(1) == "ABCD"[expected]:
            marks.append((match.start(), match.group(1)))
            expected += 1
    if len(marks) != 4:
        raise ValueError(f"选项切分失败：{text}")

    options = []
    for idx, (pos, letter) in enumerate(marks):
        end = marks[idx + 1][0] if idx + 1 < len(marks) else len(text)
        body = chars[pos + 2:end]
        content = "".join(c for c, _ in body).strip("　 ")
        bold_text = "".join(c for c, b in body if b).strip()
        options.append({"letter": letter, "text": content, "bold": bold_text})
    return options


